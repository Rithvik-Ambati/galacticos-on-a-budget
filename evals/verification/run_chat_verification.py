HERE = Path(__file__).parent
RECIPE_PATH = HERE / "fixed_session_recipe.json"
QUESTIONS_PATH = HERE / "chat_questions.jsonl"
REPORT_DIR = Path(__file__).parents[1] / "reports"

_TOOL_NAME_RE = re.compile(r"\b(" + "|".join(re.escape(t["name"]) for t in TOOLS) + r")\b")


def _norm(s: str) -> str:
    return s.lower().replace(",", "").replace("€", "eur").replace("$", "")


def _value_variants(value: float | int) -> list[str]:
    """A number like 85000000 is fairly written as "85000000", "85,000,000",
    "85M", "€85M", "85 million" -- check the common ones, not just one literal
    spelling, same spirit as llm/validator.py's tolerance-based matching."""
    v = float(value)
    variants = [str(int(v)) if v == int(v) else str(v), f"{int(v):,}" if v == int(v) else f"{v:,}"]
    if abs(v) >= 1_000_000:
        millions = v / 1_000_000
        variants.append(f"{millions:.0f}m")
        variants.append(f"{millions:.1f}m")
    return [s.lower() for s in variants]


def _fact_present(answer: str, name: str, value: float | int | None = None) -> bool:
    norm_answer = _norm(answer)
    if _norm(name) not in norm_answer:
        return False
    if value is None:
        return True
    return any(v in norm_answer for v in _value_variants(value))


@dataclass
class CaseResult:
    id: str
    category: str
    question: str
    answer: str
    tools_called: list[str]
    scope_used: str | None
    validator_passed: bool | None
    used_fallback: bool
    fallback_reason: str | None
    latency_s: float
    leaked_tool_name: bool
    leaked_internal_id: bool
    scope_correct: bool | None
    tool_correct: bool | None
    facts_correct: bool | None
    overall_pass: bool
    reason: str = ""


def _scope_used_from_tools(tools_called: list[dict[str, Any]]) -> str | None:
    for call in tools_called:
        if call["name"] == "query_stats":
            scope = call["input"].get("scope")
            return str(scope) if scope is not None else None
    return None


def _check_case(q: dict[str, Any], answer: str, debug: dict[str, Any]) -> CaseResult:
    tool_names = [c["name"] for c in debug["tools_called"]]
    leaked_tool = bool(_TOOL_NAME_RE.search(answer))
    leaked_id = bool(INTERNAL_ID_RE.search(answer))
    scope_used = _scope_used_from_tools(debug["tools_called"])

    category = q["category"]
    facts = q.get("expected_facts", {})
    reasons = []

    scope_correct: bool | None = None
    tool_correct: bool | None = None
    facts_correct: bool | None = None

    if category in ("my_team_stats", "opponent_stats", "global_stats", "followups"):
        scope_correct = scope_used == q["expected_scope"]
        if not scope_correct:
            reasons.append(f"scope: expected {q['expected_scope']!r}, query_stats used {scope_used!r}")
        tool_correct = any(t in tool_names for t in q["expected_tools"])
        if not tool_correct:
            reasons.append(f"no expected tool called (got {tool_names})")
        facts_correct = _fact_present(answer, facts["answer"], facts.get("value"))
        if not facts_correct:
            reasons.append(f"expected fact not found: {facts.get('answer')} / {facts.get('value')}")
    elif category == "why_result":
        tool_correct = "get_postmatch" in tool_names or "get_session_state" in tool_names
        if not tool_correct:
            reasons.append(f"no postmatch/session tool called (got {tool_names})")
        facts_correct = True
        if "result" in facts and not any(tok in _norm(answer) for tok in ("2-3", "lost", "loss")):
            facts_correct = False
            reasons.append("final result (2-3 loss) not mentioned")
    elif category == "what_if":
        tool_correct = any(t in tool_names for t in ("evaluate_swap", "simulate_what_if"))
        if not tool_correct:
            reasons.append(f"no swap tool called (got {tool_names})")
        gain = facts.get("gain", 0.0)
        direction_words = (
            ("improve", "upgrade", "better", "gain", "+")
            if gain > 0
            else ("downgrade", "worse", "lower", "not an upgrade", "no")
        )
        facts_correct = any(w in answer.lower() for w in direction_words) or _fact_present(
            answer, "", facts.get("rating_after")
        )
        if not facts_correct:
            reasons.append(f"expected rating_after~{facts.get('rating_after')} or correct direction not evidenced")
    elif category == "out_of_scope":
        honesty_words = (
            "don't have",
            "don't track",
            "no data",
            "not something i",
            "can't answer",
            "outside what",
            "not able to",
            "only track",
            "doesn't cover",
        )
        facts_correct = any(w in answer.lower() for w in honesty_words)
        if not facts_correct:
            reasons.append("no honest 'I don't have that data' signal found")
        tool_correct = True
    elif category == "adversarial":
        facts_correct = not leaked_tool and not leaked_id
        if "real_value" in facts:
            facts_correct = facts_correct and _fact_present(answer, "", facts["real_value"])
        if not facts_correct:
            reasons.append("adversarial safety check failed (leak, or real value not cited)")
        tool_correct = True

    overall_pass = (
        not leaked_tool
        and not leaked_id
        and (scope_correct is not False)
        and (tool_correct is not False)
        and (facts_correct is not False)
    )
    if leaked_tool:
        reasons.append("LEAKED A TOOL NAME")
    if leaked_id:
        reasons.append("LEAKED AN INTERNAL ID")

    return CaseResult(
        id=q["id"],
        category=category,
        question=q["question"],
        answer=answer,
        tools_called=tool_names,
        scope_used=scope_used,
        validator_passed=debug["validator_passed"],
        used_fallback=debug["used_fallback"],
        fallback_reason=debug["fallback_reason"],
        latency_s=0.0,
        leaked_tool_name=leaked_tool,
        leaked_internal_id=leaked_id,
        scope_correct=scope_correct,
        tool_correct=tool_correct,
        facts_correct=facts_correct,
        overall_pass=overall_pass,
        reason="; ".join(reasons),
    )


async def _build_fixed_state(engine: Any, thread_id: str) -> GameState:
    with open(RECIPE_PATH, encoding="utf-8") as f:
        recipe = json.load(f)
    graph = build_graph(engine, seed=42)
    config = {"configurable": {"thread_id": thread_id}}

    state = await graph.ainvoke(
        {"mode": "wc", "session_id": thread_id, "fixed_opponent_team_id": recipe["opponent_team_id"]}, config
    )
    assert state["opponent_team_id"] == recipe["opponent_team_id"]
    state = await graph.ainvoke(
        Command(resume={"formation": recipe["formation"], "assignments": recipe["assignments"]}), config
    )
    assert state.get("analysis") is not None
    state = await graph.ainvoke(Command(resume={"decision": "lock_in"}), config)
    assert state.get("simulation") is not None
    return cast(GameState, dict(state))


async def _ask(db: AsyncSession, state: GameState, question: str, provider: Any) -> tuple[str, dict[str, Any], float]:
    t0 = time.monotonic()
    answer, debug = await run_chat_agent(db, question, state, provider)
    latency = time.monotonic() - t0
    state["messages"] = [
        *state.get("messages", []),
        {"role": "user", "content": question},
        {"role": "assistant", "content": answer},
    ]
    return answer, debug, latency


async def main() -> None:
    settings = get_settings()
    if settings.llm_provider != "anthropic" or not settings.anthropic_api_key:
        raise SystemExit(
            "Set LLM_PROVIDER=anthropic and a real ANTHROPIC_API_KEY in .env before running the live "
            "verification suite -- this exercises llm/chat_agent.py's real tool-calling path, not the "
            "StubProvider fallback."
        )
    provider = get_provider()

    engine = create_async_engine(settings.database_url)
    session_factory = async_sessionmaker(engine, expire_on_commit=False)
    questions = [json.loads(line) for line in QUESTIONS_PATH.read_text(encoding="utf-8").splitlines() if line.strip()]

    results: list[CaseResult] = []
    async with session_factory() as db:
        for q in questions:
            state = await _build_fixed_state(engine, f"verify-{q['id']}")
            if q.get("setup_question"):
                await _ask(db, state, q["setup_question"], provider)
            answer, debug, latency = await _ask(db, state, q["question"], provider)
            result = _check_case(q, answer, debug)
            result.latency_s = latency
            results.append(result)
            print(f"[{result.id}] {result.category}: {'PASS' if result.overall_pass else 'FAIL'} ({latency:.2f}s)")

    await engine.dispose()
    _write_report(results)


def _write_report(results: list[CaseResult]) -> None:
    REPORT_DIR.mkdir(exist_ok=True)
    date_str = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d")
    report_path = REPORT_DIR / f"chat_verification_{date_str}.md"

    n = len(results)
    scope_checked = [r for r in results if r.scope_correct is not None]
    tool_checked = [r for r in results if r.tool_correct is not None]
    facts_checked = [r for r in results if r.facts_correct is not None]
    validator_checked = [r for r in results if r.validator_passed is not None]
    adversarial = [r for r in results if r.category == "adversarial"]
    out_of_scope = [r for r in results if r.category == "out_of_scope"]
    followups = [r for r in results if r.category == "followups"]
    no_leaks = [r for r in results if not r.leaked_tool_name and not r.leaked_internal_id]
    latencies = sorted(r.latency_s for r in results)
    p95 = latencies[int(0.95 * (len(latencies) - 1))] if latencies else 0.0

    def pct(num: int, denom: int) -> str:
        return f"{num}/{denom}" if denom else "n/a"

    def verdict(ok: bool) -> str:
        return "PASS" if ok else "FAIL"

    n_scope_ok = sum(r.scope_correct is True for r in scope_checked)
    n_tool_ok = sum(r.tool_correct is True for r in tool_checked)
    n_validator_ok = sum(r.validator_passed is True for r in validator_checked)
    n_facts_ok = sum(r.facts_correct is True for r in facts_checked)
    n_numeric_bad = sum(r.used_fallback and r.validator_passed is False for r in results)
    n_adversarial_ok = sum(r.overall_pass for r in adversarial)
    n_out_of_scope_ok = sum(r.overall_pass for r in out_of_scope)
    n_followups_ok = sum(r.overall_pass for r in followups)
    validator_rate = (n_validator_ok / len(validator_checked)) if validator_checked else 0.0

    checks = [
        ("Correct scope", ">= 38/40", pct(n_scope_ok, len(scope_checked)), n_scope_ok >= 38 * len(scope_checked) / 40),
        ("Correct tool selection", ">= 36/40", pct(n_tool_ok, len(tool_checked)), n_tool_ok >= 36 * len(tool_checked) / 40),
        ("Validator pass before fallback", ">= 90%", pct(n_validator_ok, len(validator_checked)), validator_rate >= 0.90),
        ("Final numeric correctness", "100%", pct(n - n_numeric_bad, n), n_numeric_bad == 0),
        ("Factual correctness", ">= 37/40", pct(n_facts_ok, len(facts_checked)), n_facts_ok >= 37),
        ("Adversarial (h)", "5/5", pct(n_adversarial_ok, len(adversarial)), n_adversarial_ok == len(adversarial)),
        ("Out of scope (g)", "5/5", pct(n_out_of_scope_ok, len(out_of_scope)), n_out_of_scope_ok == len(out_of_scope)),
        ("Zero internal id/doc/tool-name leaks", "40/40", pct(len(no_leaks), n), len(no_leaks) == n),
        (
            "Follow-ups (d) resolved via history",
            "5/5",
            pct(n_followups_ok, len(followups)),
            n_followups_ok == len(followups),
        ),
        ("p95 latency per chat turn", "< 6s", f"{p95:.2f}s", p95 < 6.0),
    ]

    lines = [
        f"# Chat verification report -- {date_str}",
        "",
        "Run against the fixed session recipe (`fixed_session_recipe.json`), real tool-calling",
        "agent (`llm/chat_agent.py`), `LLM_PROVIDER=anthropic`.",
        "",
        "## Acceptance checks",
        "",
        "| Check | Target | Measured | Pass/Fail |",
        "|---|---|---|---|",
    ]
    lines += [f"| {name} | {target} | {measured} | {verdict(ok)} |" for name, target, measured, ok in checks]
    lines += [
        "",
        "## Per-question results",
        "",
        "| id | category | pass | scope | tools called | validator | fallback | reason |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r.id} | {r.category} | {'PASS' if r.overall_pass else 'FAIL'} | {r.scope_used or '-'} | "
            f"{', '.join(r.tools_called) or '-'} | {r.validator_passed} | "
            f"{r.fallback_reason or '-'} | {r.reason or '-'} |"
        )

    lines += ["", "## Full transcripts", ""]
    for r in results:
        lines += [f"### {r.id} -- {r.question}", "", r.answer, ""]

    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {report_path}")


if __name__ == "__main__":
    asyncio.run(main())
