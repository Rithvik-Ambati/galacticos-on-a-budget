"""Runs evals/verification/chat_questions.jsonl against the real tool-calling chat
agent (llm/chat_agent.py, requires LLM_PROVIDER=anthropic) over the fixed session
recipe in this directory, and writes evals/reports/chat_verification_<date>.md with
every acceptance check from the project owner's verification task.

This is deliberately separate from evals/golden/ (CLAUDE.md: golden sets are
human-written, never generated) -- these 40 questions, their expected scope/tools,
and their expected facts were written by hand against this fixed session's real
database rows (see fixed_session_recipe.json's docstring-equivalent comment below),
not generated by a model.

Usage: python -m evals.verification.run_chat_verification
"""

